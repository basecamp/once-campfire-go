func allEmoji(text string) bool {
	if text == "" {
		return false
	}
	for _, r := range text {
		i := sort.Search(len(emojiRanges), func(i int) bool { return emojiRanges[i][1] >= r })
		if i == len(emojiRanges) || emojiRanges[i][0] > r {
			return false
		}
	}
	return true
}
